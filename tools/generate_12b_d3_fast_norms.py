#!/usr/bin/env python3
"""Derive fixed-four-row cached boundaries from the accepted exact T1 kernels."""
from pathlib import Path
import argparse
import hashlib
import json


def close(source, start):
    depth = 0
    for i in range(start, len(source)):
        depth += (source[i] == "{") - (source[i] == "}")
        if depth == 0:
            return i
    raise ValueError("unclosed CUDA function")


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    parent = root / "src/cuda/norm/twelve_b_ordinary.cu"
    source = parent.read_text()
    prefix = source[:source.index("__global__ void TwelveBOrdinaryInputNormFp8Kernel")]
    prefix = prefix.replace('"cuda/norm/twelve_b_ordinary.h"', '"cuda/norm/twelve_b_d3_fast.h"')
    kernels = []
    for suffix, offset in [
        ("InputNormFp8", "input+=blockIdx.x*3840U;output+=blockIdx.x*3840U;scale+=blockIdx.x;"),
        ("AttentionQuantize", "input+=blockIdx.x*kElements;output+=blockIdx.x*kElements;scale+=blockIdx.x;"),
        ("PostAttention", "const unsigned r=blockIdx.x;projection+=r*3840U;residual+=r*3840U;if(post_output)post_output+=r*3840U;hidden_output+=r*3840U;packed+=r*1920U;scales+=r*240U;"),
        ("PostMlp", "const unsigned r=blockIdx.x;input+=r*3840U;residual+=r*3840U;if(post_output)post_output+=r*3840U;output+=r*3840U;"),
    ]:
        old = "TwelveBOrdinary" + suffix + "Kernel"
        begin = source.rfind("__global__", 0, source.index("void " + old + "("))
        brace = source.index("{", begin)
        kernel = source[begin:close(source, brace) + 1]
        kernel = kernel.replace(old, "TwelveBD3Fast" + suffix + "Kernel", 1)
        brace = kernel.index("{")
        kernel = kernel[:brace + 1] + "\n  " + offset + "\n" + kernel[brace + 1:]
        if suffix == "AttentionQuantize":
            kernel = "template <unsigned kElements>\n" + kernel
        if suffix == "PostMlp":
            kernel = kernel.replace("const float* input", "const std::uint16_t* input", 1)
            kernel = kernel.replace("values[j] = input[threadIdx.x + j * kThreads];",
                "values[j] = static_cast<float>(__ushort_as_bfloat16(input[threadIdx.x + j * kThreads]));")
        kernels.append(kernel)
    launches = source[source.index("Status LaunchTwelveBOrdinaryInputNormFp8("):]
    launches = launches.replace("LaunchTwelveBOrdinary", "LaunchTwelveBD3Fast").replace("TwelveBOrdinary", "TwelveBD3Fast")
    launches = launches.replace("<<<1,", "<<<4,").replace("12B Ordinary", "12B D3 cached")
    launches = launches.replace("const float* input,\n    const std::uint16_t* weight, const float* residual", "const std::uint16_t* input,\n    const std::uint16_t* weight, const float* residual")
    # Match the parent's launch-error helper, without copying any T1 kernel.
    helper_start = source.index("Status LaunchStatus(")
    helper_end = close(source, source.index("{", helper_start)) + 1
    text = ("// Generated by tools/generate_12b_d3_fast_norms.py; do not edit.\n" +
            prefix + "\n\n".join(kernels) + "\n" + source[helper_start:helper_end] +
            "\n} // namespace\n\n" + launches)
    args.output.write_text(text)
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    args.output.with_suffix(".provenance.json").write_text(json.dumps({
        "inputs": {str(p.relative_to(root)): sha(p) for p in [parent, Path(__file__)]},
        "output_sha256": sha(args.output),
        "scope": "fixed T4 cached exact-tree norm/quant boundaries; BF16 physical Down input; experimental D3 path only",
        "weights_precision_layout_reduction_rounding_unchanged": True,
    }, indent=2) + "\n")


if __name__ == "__main__":
    main()
