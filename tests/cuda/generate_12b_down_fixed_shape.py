"""Emit exactly the offline-tested fixed T3 Down kernel; no benchmark-file input."""
from pathlib import Path
import argparse
import ast

ROOT = Path(__file__).resolve().parents[2]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('destination', type=Path)
a = p.parse_args()
tree = ast.parse((ROOT / 'tests/cuda/build_12b_down_dual_tile.py').read_text())
parts = [n.value.right.value for n in tree.body if isinstance(n, ast.Assign)
         and any(isinstance(t, ast.Name) and t.id == 's' for t in n.targets)
         and isinstance(n.value, ast.BinOp) and isinstance(n.value.right, ast.Constant)]
assert len(parts) == 1
s = parts[0]
s = s.replace('Sm120D2DownDualTileKernel', 'Sm120D2DownFixedShapeKernel')
assert s.count('const unsigned tile0=(blockIdx.x*4U+warp)*2U;') == 1
s = s.replace('const unsigned tile0=(blockIdx.x*4U+warp)*2U;', 'const unsigned tile0=blockIdx.x*8U+warp;')
s = s.replace('float accum[2][4]={};', 'float accum[1][4]={};').replace('n<2U', 'n<1U')
start = s.index('__global__ void Sm120D2DownFixedShapeKernel(')
end = s.index('\n}}', start)
text = '// Generated by tests/cuda/generate_12b_down_fixed_shape.py; do not edit.\n'
text += '// Exact T3/N3840/K15360; parent geometry, K64 MMA order and BF16 epilogue.\n'
text += s[start:end] + '\n'
fixed_t3 = s[start:end]
assert fixed_t3.count('group<3U') == 4
text += '\n' + fixed_t3.replace('Sm120D2DownFixedShapeKernel',
                               'Sm120D4DownFixedShapeKernel').replace('group<3U', 'group<5U') + '\n'
text += '\n' + fixed_t3.replace('Sm120D2DownFixedShapeKernel',
                               'Sm120D3DownFixedShapeKernel').replace('group<3U', 'group<4U') + '\n'
a.destination.parent.mkdir(parents=True, exist_ok=True)
with a.destination.open('x') as f: f.write(text)
