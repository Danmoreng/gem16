"""Emit the single numerically tested12B post-attention fusion into production."""
from pathlib import Path
import argparse,subprocess,sys,tempfile
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('destination',type=Path);a=p.parse_args()
with tempfile.TemporaryDirectory(prefix='gem16-post-attention-') as tmp:
 base=Path(tmp)/'base.cu';subprocess.run([sys.executable,str(ROOT/'tests/cuda/build_12b_norm_candidate.py'),str(base)],check=True);s=base.read_text()
 begin=s.index('__device__ float TwelveBParentBlockSum(');end=s.index('template <typename Input>\n__global__ void TwelveBParentNormKernel(',begin)
 reduction=s[begin:end].replace('kThreads','256U').replace('TwelveBParentBlockSum','TwelveBPostAttentionBlockSum')
 begin=s.index('__global__ void TwelveBPostAttentionQuantizeCandidateKernel(');end=s.index('\n} } // private / internal',begin)
 kernel=s[begin:end].replace('TwelveBPostAttentionQuantizeCandidateKernel','TwelveBPostAttentionQuantizeKernel').replace('TwelveBParentBlockSum','TwelveBPostAttentionBlockSum')
 text='// Generated by tests/cuda/generate_12b_post_attention.py; do not edit.\n// Exact existing projection/postnorm/residual/pre-MLP rounding and reduction.\n'+reduction+'\n'+kernel
 # D2 retains an independent copy of the same 256-thread arithmetic per row.
 # Weights are shared across rows; only activation/output strides change.
 batch=kernel.replace('TwelveBPostAttentionQuantizeKernel','TwelveBPostAttentionQuantizeT3Kernel',1)
 marker='float global_divisor){'
 assert batch.count(marker)==1
 batch=batch.replace(marker,marker+'''\n const std::uint64_t row=blockIdx.x;
 projection+=row*3840U;residual+=row*3840U;
 if(post_output!=nullptr)post_output+=row*3840U;
 hidden_output+=row*3840U;packed_e2m1+=row*1920U;
 block_scales_e4m3fn+=row*240U;
''')
 text+='\n\n'+batch
 text+='\n\n'+batch.replace('TwelveBPostAttentionQuantizeT3Kernel',
                           'TwelveBPostAttentionQuantizeT5Kernel',1)
 text+='\n\n'+batch.replace('TwelveBPostAttentionQuantizeT3Kernel',
                           'TwelveBPostAttentionQuantizeT4Kernel',1)
 a.destination.parent.mkdir(parents=True,exist_ok=True)
 with a.destination.open('x') as f:f.write(text)
